/**
 * Generate app/static/arch/architecture-viewer.html.
 *
 * Takes the PRISTINE vendored renderer (vendor/solution-builder/architecture-viewer.html —
 * solution-builder's own self-contained @xyflow/react architecture canvas), swaps the
 * placeholder `{}` inside its inline `<script type="application/json" id="architecture">`
 * block for arch/isaac-supervisor.arch.json, and adds a self-hosted DM Sans @font-face so
 * the diagram gets the right typeface without a call to fonts.googleapis.com (the bundle
 * asks for "DM Sans" but ships no font file, so unmodified it silently falls back to
 * system-ui).
 *
 * The vendored copy is never edited in place — the DB licence requires modified files to
 * say so, and the generated file carries that banner.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'vendor/solution-builder/architecture-viewer.html');
const SPEC = join(ROOT, 'arch/isaac-supervisor.arch.json');
const OUT = join(ROOT, 'app/static/arch/architecture-viewer.html');

const html = readFileSync(SRC, 'utf8');
const spec = readFileSync(SPEC, 'utf8').trim();

// Fail loudly rather than silently producing a viewer with no diagram in it.
JSON.parse(spec);
const BLOCK = /(<script type="application\/json" id="architecture">)([\s\S]*?)(<\/script>)/g;
const hits = html.match(BLOCK) ?? [];
if (hits.length !== 1) {
  throw new Error(`expected exactly 1 architecture JSON block in the renderer, found ${hits.length}`);
}

const banner = `<!--
  MODIFIED COPY — generated by scripts/build-arch.mjs, do not edit by hand.
  Source: vendor/solution-builder/architecture-viewer.html (databricks-solutions/solution-builder,
  commit 711fa032b676c2023f7d239a8c1ebabda8ded508, DB licence — see vendor/solution-builder/LICENSE).
  Changes: (1) the inline architecture JSON is arch/isaac-supervisor.arch.json instead of the
  placeholder {}; (2) a self-hosted DM Sans @font-face was added so the canvas renders in the
  typeface it asks for without any CDN request. Nothing else is touched.
-->
`;

const fontFace = `    <style>
      /* Self-hosted — see /fonts/README.txt. The upstream bundle sets
         font-family: "DM Sans" but embeds no font, so without this the canvas
         quietly renders in system-ui. */
      @font-face {
        font-family: "DM Sans";
        font-style: normal;
        font-weight: 100 1000;
        font-display: swap;
        src: url("/fonts/DMSans-100_1000-latin.woff2") format("woff2");
      }
      html, body { margin: 0; background: #fff; }
    </style>
`;

let out = html.replace(BLOCK, (_m, open, _old, close) => `${open}\n${spec}\n    ${close}`);
if (!out.includes('"nodes"')) throw new Error('spec did not land in the output');
out = banner + out.replace('  </head>', `${fontFace}  </head>`);
if (!out.includes('@font-face')) throw new Error('font-face injection failed — </head> not found?');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);

const tabs = JSON.parse(spec);
console.log(
  `[build-arch] ${OUT.replace(ROOT + '/', '')} · ${out.length} bytes · ` +
    `${tabs.length} tab(s), ${tabs[0].nodes.length} nodes, ${tabs[0].edges.length} edges`,
);
